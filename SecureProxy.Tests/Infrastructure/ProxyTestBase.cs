using System.Net;
using System.Text;
using System.Text.Json;
using SecureProxy.Api.Proxy;
using SecureProxy.Api.Security;

namespace SecureProxy.Tests.Infrastructure;

/// <summary>Shared helpers. All integration tests share one database and run one after another.</summary>
[Collection(ProxyCollection.Name)]
public abstract class ProxyTestBase
{
    protected const string ProxyPath = "/api/proxy/execute";

    protected ProxyTestBase(ProxyTestFixture fixture)
    {
        Fixture = fixture;
        fixture.Upstream.Reset();
        Client = fixture.CreateProxyClient();
    }

    protected ProxyTestFixture Fixture { get; }

    protected HttpClient Client { get; }

    protected RecordingUpstreamHandler Upstream => Fixture.Upstream;

    protected static object Envelope(string operationKey, object parameters) => new { clientId = operationKey, json = parameters };

    /// <summary>Builds an envelope with AES-256-GCM encrypted parameters, bound to <paramref name="associatedKey"/> (default: the operation key).</summary>
    protected static object EncryptedEnvelope(string operationKey, object parameters, string? associatedKey = null, byte[]? key = null)
    {
        var plaintext = JsonSerializer.SerializeToUtf8Bytes(parameters);
        var (nonce, ciphertext, tag) = AesGcmPayload.Encrypt(
            key ?? ProxyTestFixture.EncryptionKey, plaintext, AesGcmPayload.AssociatedData(associatedKey ?? operationKey));
        return EncryptedEnvelope(operationKey, nonce, ciphertext, tag);
    }

    protected static object EncryptedEnvelope(string operationKey, byte[] nonce, byte[] ciphertext, byte[] tag) => new
    {
        clientId = operationKey,
        encryptedJson = new
        {
            nonce = Convert.ToBase64String(nonce),
            ciphertext = Convert.ToBase64String(ciphertext),
            tag = Convert.ToBase64String(tag),
        },
    };

    protected Task<ProxyResult> ExecuteAsync(object envelope, Action<HttpRequestMessage>? configure = null) =>
        ExecuteRawAsync(JsonSerializer.Serialize(envelope), configure: configure);

    protected async Task<ProxyResult> ExecuteRawAsync(
        string body, string contentType = "application/json", Action<HttpRequestMessage>? configure = null, HttpMethod? method = null)
    {
        var correlationId = "test-" + Guid.NewGuid().ToString("N");
        using var request = new HttpRequestMessage(method ?? HttpMethod.Post, ProxyPath)
        {
            Content = new StringContent(body, Encoding.UTF8, contentType),
        };
        request.Headers.Add(HeaderPolicy.CorrelationIdHeader, correlationId);
        configure?.Invoke(request);

        var response = await Client.SendAsync(request);
        return new ProxyResult(response, await response.Content.ReadAsStringAsync(), correlationId);
    }

    /// <summary>The destination received nothing: the proof the brief asks for, beyond the status code.</summary>
    protected void AssertNotForwarded() => Assert.Empty(Upstream.Requests);

    protected RecordedRequest AssertForwardedOnce() => Assert.Single(Upstream.Requests);

    protected static void AssertProxyError(ProxyResult result, HttpStatusCode status, string code)
    {
        Assert.Equal(status, result.Response.StatusCode);
        Assert.Equal("proxy", result.Source);
        Assert.Equal("application/problem+json", result.Response.Content.Headers.ContentType?.MediaType);
        Assert.Equal(code, result.Json.GetProperty("code").GetString());
        Assert.Equal(result.CorrelationId, result.Json.GetProperty("correlationId").GetString());
    }
}

public sealed record ProxyResult(HttpResponseMessage Response, string Body, string CorrelationId)
{
    public JsonElement Json => JsonDocument.Parse(Body).RootElement;

    /// <summary>"proxy" for errors generated by the proxy, "upstream" for responses from the destination.</summary>
    public string? Source => Response.Headers.TryGetValues(ProblemWriter.ResponseSourceHeader, out var values) ? values.Single() : null;
}
