using System.Reflection;
using System.Text.Json;
using System.Text.Json.Serialization;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using SecureProxy.Api.Domain;

namespace SecureProxy.Api.Data;

public sealed class ProxyDbContext(
    DbContextOptions<ProxyDbContext> options,
    TimeProvider timeProvider,
    IChangeActorAccessor? actorAccessor = null) : DbContext(options)
{
    /// <summary>Writes enum values in the history as names (Integer) rather than numbers (1).</summary>
    private static readonly JsonSerializerOptions HistoryJson = new() { Converters = { new JsonStringEnumConverter() } };

    public DbSet<Destination> Destinations => Set<Destination>();

    public DbSet<Operation> Operations => Set<Operation>();

    public DbSet<ParameterRule> ParameterRules => Set<ParameterRule>();

    public DbSet<HeaderRule> HeaderRules => Set<HeaderRule>();

    public DbSet<EncryptionProfile> EncryptionProfiles => Set<EncryptionProfile>();

    public DbSet<OperationalSetting> OperationalSettings => Set<OperationalSetting>();

    public DbSet<RequestLog> RequestLogs => Set<RequestLog>();

    public DbSet<ConfigurationChange> ConfigurationChanges => Set<ConfigurationChange>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(ProxyDbContext).Assembly);
    }

    public override int SaveChanges(bool acceptAllChangesOnSuccess)
    {
        var pending = PrepareChanges(acceptAllChangesOnSuccess);
        if (pending.Count == 0)
        {
            return base.SaveChanges(acceptAllChangesOnSuccess);
        }

        // The history rows need the keys generated by the first save, so both saves
        // run in one transaction: the change and its history commit or fail together.
        using var transaction = Database.CurrentTransaction is null ? Database.BeginTransaction() : null;
        var result = base.SaveChanges(acceptAllChangesOnSuccess);
        ConfigurationChanges.AddRange(pending.Select(p => p.ToRecord()));
        base.SaveChanges(acceptAllChangesOnSuccess);
        transaction?.Commit();
        return result;
    }

    public override async Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, CancellationToken cancellationToken = default)
    {
        var pending = PrepareChanges(acceptAllChangesOnSuccess);
        if (pending.Count == 0)
        {
            return await base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
        }

        await using var transaction = Database.CurrentTransaction is null
            ? await Database.BeginTransactionAsync(cancellationToken)
            : null;
        var result = await base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
        ConfigurationChanges.AddRange(pending.Select(p => p.ToRecord()));
        await base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
        if (transaction is not null)
        {
            await transaction.CommitAsync(cancellationToken);
        }

        return result;
    }

    /// <summary>Sets timestamps and captures history for every changed configuration entity.</summary>
    private List<PendingChange> PrepareChanges(bool acceptAllChangesOnSuccess)
    {
        // Writing history needs a second save, which would insert the same entities
        // again if the first save did not accept its changes.
        if (!acceptAllChangesOnSuccess && ChangeTracker.Entries<IConfigurationEntity>().Any(e => e.State != EntityState.Unchanged))
        {
            throw new NotSupportedException("Configuration changes must be saved with acceptAllChangesOnSuccess = true.");
        }

        var now = timeProvider.GetUtcNow().UtcDateTime;
        var actor = actorAccessor?.CurrentActor ?? "system";
        var pending = new List<PendingChange>();

        foreach (var entry in ChangeTracker.Entries<IConfigurationEntity>())
        {
            switch (entry.State)
            {
                case EntityState.Added:
                    entry.Entity.CreatedAt = now;
                    entry.Entity.UpdatedAt = now;
                    break;
                case EntityState.Modified:
                    entry.Entity.UpdatedAt = now;
                    entry.Property(e => e.CreatedAt).IsModified = false;
                    break;
                case EntityState.Deleted:
                    break;
                default:
                    continue;
            }

            var changeType = ToChangeType(entry.State);
            if (changeType == ConfigurationChangeType.Added)
            {
                // Keys and foreign keys of new entities are temporary until saved,
                // so their history is described after the first save.
                pending.Add(new PendingChange(entry, changeType, null, null, now, actor));
                continue;
            }

            var changes = DescribeChanges(entry, changeType);
            if (changeType == ConfigurationChangeType.Modified && changes.Count == 0)
            {
                continue;
            }

            pending.Add(new PendingChange(entry, changeType, DescribeKey(entry), JsonSerializer.Serialize(changes, HistoryJson), now, actor));
        }

        return pending;
    }

    private static string DescribeKey(EntityEntry entry) =>
        string.Join(",", entry.Metadata.FindPrimaryKey()!.Properties.Select(p => entry.Property(p.Name).CurrentValue?.ToString()));

    private static Dictionary<string, object?> DescribeChanges(EntityEntry entry, ConfigurationChangeType changeType)
    {
        var changes = new Dictionary<string, object?>();
        foreach (var property in entry.Properties)
        {
            var info = property.Metadata.PropertyInfo;
            if (info is null || info.GetCustomAttribute<NotInHistoryAttribute>() is not null)
            {
                continue;
            }

            if (property.Metadata.Name is nameof(IConfigurationEntity.CreatedAt) or nameof(IConfigurationEntity.UpdatedAt))
            {
                continue;
            }

            switch (changeType)
            {
                case ConfigurationChangeType.Added:
                    if (!property.Metadata.IsPrimaryKey())
                    {
                        changes[property.Metadata.Name] = new { @new = property.CurrentValue };
                    }

                    break;
                case ConfigurationChangeType.Deleted:
                    changes[property.Metadata.Name] = new { old = property.OriginalValue };
                    break;
                case ConfigurationChangeType.Modified when property.IsModified && !Equals(property.OriginalValue, property.CurrentValue):
                    changes[property.Metadata.Name] = new { old = property.OriginalValue, @new = property.CurrentValue };
                    break;
            }
        }

        return changes;
    }

    private static ConfigurationChangeType ToChangeType(EntityState state) => state switch
    {
        EntityState.Added => ConfigurationChangeType.Added,
        EntityState.Deleted => ConfigurationChangeType.Deleted,
        _ => ConfigurationChangeType.Modified,
    };

    private sealed record PendingChange(
        EntityEntry Entry,
        ConfigurationChangeType ChangeType,
        string? Key,
        string? Changes,
        DateTime ChangedAt,
        string ChangedBy)
    {
        /// <summary>Called after the first save, when database-generated keys are known.</summary>
        public ConfigurationChange ToRecord() => new()
        {
            EntityType = Entry.Metadata.ClrType.Name,
            EntityKey = Key ?? DescribeKey(Entry),
            ChangeType = ChangeType,
            ChangedAt = ChangedAt,
            ChangedBy = ChangedBy,
            Changes = Changes ?? JsonSerializer.Serialize(DescribeChanges(Entry, ChangeType), HistoryJson),
        };
    }
}

/// <summary>Supplies the identity recorded as <see cref="ConfigurationChange.ChangedBy"/>.</summary>
public interface IChangeActorAccessor
{
    string? CurrentActor { get; }
}
